"""Ticket handoffs: one file per role under <item>/handoff/<role>.md, and a generated index in
<item>/HANDOFF.md. A session edits only its own role's file; nobody edits the index.
Used by tools/work/work (handoff, restore). Layout and rules: tools/work/README.md -> Handoff."""
import datetime, os, re, shutil, sys

MARK = "<!-- generated by tools/work/handoff; do not edit: each role edits its own handoff/<role>.md -->"
TEMPLATE_RE = re.compile(r"<3.6 bullets|<the literal next|<UTC time>")
LIMIT = 40   # lines per role file before restore asks to move detail out


def read(p):
    return open(p, encoding="utf-8", errors="replace").read() if os.path.exists(p) else ""


def utc(p):
    return datetime.datetime.fromtimestamp(os.path.getmtime(p), datetime.timezone.utc).strftime("%Y-%m-%dT%H:%MZ")


def role_file(d, role):
    return os.path.join(d, "handoff", role + ".md")


def roles(d):
    hd = os.path.join(d, "handoff")
    return sorted(f[:-3] for f in os.listdir(hd) if f.endswith(".md")) if os.path.isdir(hd) else []


def legacy(d):
    """Text of a pre-role HANDOFF.md (written by hand, not the generated index), else ''."""
    t = read(os.path.join(d, "HANDOFF.md"))
    return "" if MARK in t else t.strip()


def status(text):
    """One-line status of a role file: its **Status:** line, else the first Resume-here bullet."""
    if TEMPLATE_RE.search(text): return "(empty template)"
    m = re.search(r"(?mi)^\**status:?\**:?[ \t]*(\S.*)$", text)
    if not m:
        sec = re.search(r"(?ms)^## Resume here\s*\n(.*?)(^## |\Z)", text)
        m = re.search(r"(?m)^\s*[-*]\s+(.+)$", sec.group(1)) if sec else None
    s = m.group(1).strip() if m else "(no status line)"
    return s if len(s) <= 160 else s[:157] + "..."


def state_field(d, key):
    m = re.search(r"(?m)^%s:[ \t]*([^#\n]*)" % key, read(os.path.join(d, "STATE.md")))
    return m.group(1).strip() if m else ""


def index_text(root, rel):
    d = os.path.join(root, rel)
    iid, title = os.path.basename(d), state_field(d, "title")
    out = [f"# {iid}: {title} (handoff index)" if title else f"# {iid} (handoff index)", "", MARK, "",
           "Each role keeps its own resume point in `handoff/<role>.md` and edits only that file.",
           "History is in `LOG.md`, status and links in `STATE.md`, detail in `reports/` and `evidence/`.", ""]
    rs = roles(d)
    out += ["## Roles", ""] + ([f"- **{r}** (`handoff/{r}.md`, {utc(role_file(d, r))}): {status(read(role_file(d, r)))}"
                               for r in rs] or ["- none yet (`tools/work/handoff` creates the role file)"])
    subs = sorted(s for s in os.listdir(d) if os.path.isfile(os.path.join(d, s, "STATE.md"))) if os.path.isdir(d) else []
    if subs:
        out += ["", "## Sub-items", ""] + [f"- `{s}/` [{state_field(os.path.join(d, s), 'status') or '?'}]: "
                                           f"{state_field(os.path.join(d, s), 'title')}" for s in subs]
    return "\n".join(out) + "\n"


def write_index(root, rel):
    open(os.path.join(root, rel, "HANDOFF.md"), "w", encoding="utf-8").write(index_text(root, rel))


def fill(tpl, iid, title, role, date):
    for k, v in {"<id>": iid, "<title>": title, "<role>": role, "<YYYY-MM-DD>": date}.items():
        tpl = tpl.replace(k, v)
    return tpl


def cmd_handoff(root, rel, role, tpl_path):
    """Migrate a legacy HANDOFF.md, create the role file if missing, archive a copy of it when it
    changed since the last copy, and rebuild the index."""
    d = os.path.join(root, rel)
    iid, title = os.path.basename(d), state_field(d, "title")
    rf, hist = role_file(d, role), os.path.join(d, "history")
    os.makedirs(os.path.dirname(rf), exist_ok=True)
    old = legacy(d)
    if old and not roles(d):
        if TEMPLATE_RE.search(old): print("dropped the empty legacy HANDOFF.md")
        else:
            open(role_file(d, "main"), "w", encoding="utf-8").write(old + "\n")
            print(f"moved the legacy HANDOFF.md to {rel}/handoff/main.md")
    if not os.path.exists(rf):
        tpl = read(tpl_path) or "# <id>: <title> (<role>)\n\n**Status:**\n\n## Resume here\n\n**Immediate next action:**\n"
        open(rf, "w", encoding="utf-8").write(fill(tpl, iid, title, role, datetime.date.today().isoformat()))
        print(f"created {rel}/handoff/{role}.md: fill it in place")
    else:
        prev = sorted(f for f in os.listdir(hist) if f.startswith(f"handoff-{role}-")) if os.path.isdir(hist) else []
        if not prev or read(os.path.join(hist, prev[-1])) != read(rf):
            os.makedirs(hist, exist_ok=True)
            dst = os.path.join(hist, f"handoff-{role}-{datetime.datetime.now(datetime.timezone.utc).strftime('%Y%m%dT%H%M%SZ')}.md")
            shutil.copyfile(rf, dst)
            print(f"archived a copy: {os.path.relpath(dst, root).replace(os.sep, '/')}")
        print(f"your handoff: {rel}/handoff/{role}.md (edit in place; only this role's file)")
    write_index(root, rel)


if __name__ == "__main__":
    cmd, args = sys.argv[1], sys.argv[2:]
    if cmd == "handoff": cmd_handoff(*args)
    elif cmd == "index": write_index(*args)
    else: sys.exit(f"lib_handoff: unknown command {cmd}")
